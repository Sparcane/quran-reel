interface RawSurah {
  number: number;
  nameAr: string;
  nameEn: string;
  verseCount: number;
  revelation: 'meccan' | 'medinan';
}

export function parseSurahMetadata(xml: string): RawSurah[] {
  const pattern =
    /<sura index="(\d+)" ayas="(\d+)" start="\d+" name="([^"]*)" tname="([^"]*)" ename="[^"]*" type="(Meccan|Medinan)"/g;
  const surahs: RawSurah[] = [];
  for (const match of xml.matchAll(pattern)) {
    surahs.push({
      number: Number(match[1]),
      verseCount: Number(match[2]),
      nameAr: match[3],
      nameEn: match[4],
      revelation: match[5] === 'Meccan' ? 'meccan' : 'medinan',
    });
  }
  return surahs;
}

export function renderCatalog(surahs: RawSurah[], frenchNames: readonly string[]): string {
  if (surahs.length !== 114) {
    throw new Error(`expected 114 surahs in Tanzil metadata, found ${surahs.length}`);
  }
  if (frenchNames.length !== 114) {
    throw new Error(`expected 114 French names, found ${frenchNames.length}`);
  }
  const lines = surahs.map((s, i) => {
    const nameFr = frenchNames[i];
    return `  { number: ${s.number}, nameAr: ${JSON.stringify(s.nameAr)}, nameFr: ${JSON.stringify(nameFr)}, nameEn: ${JSON.stringify(s.nameEn)}, verseCount: ${s.verseCount}, revelation: '${s.revelation}' },`;
  });
  return [
    '// Generated by scripts/generate-surah-meta.ts — do not edit by hand.',
    '// Source: Tanzil Quran metadata (quran-data.xml), text under CC BY 3.0.',
    "import type { SurahMeta } from './types';",
    '',
    'export const SURAH_META: readonly SurahMeta[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

const isMain = process.argv[1] && import.meta.url === new URL(`file:///${process.argv[1].replace(/\\/g, '/')}`).href;

if (isMain) {
  const xml = readFileSync(`${root}/data/source/quran-data.xml`, 'utf8');
  const surahs = parseSurahMetadata(xml);
  const output = renderCatalog(surahs, FRENCH_NAMES);
  writeFileSync(`${root}/packages/core/src/surah-meta.ts`, output, 'utf8');
  console.log(`wrote packages/core/src/surah-meta.ts (${surahs.length} surahs)`);
}
